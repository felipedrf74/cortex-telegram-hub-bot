#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const CAPABILITY_SKILL_METADATA_OUTPUT = 'src/generated/capability-skill-metadata.ts';

const ALLOWED_TIERS = new Set(['free', 'pro', 'max', 'owner']);

function assertNonEmptyString(value, label) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`CapabilityManifest ${label} must be a non-empty string`);
  }
}

export function buildCapabilitySkillMetadata(manifest) {
  if (manifest?.schema !== 'nexus.capability-manifest.v2' || !Array.isArray(manifest.capabilities)) {
    throw new Error('CapabilityManifest v2 is required to generate skill metadata');
  }

  const metadata = {};
  for (const entry of manifest.capabilities) {
    const domain = entry?.runtimeRouting?.domain;
    assertNonEmptyString(domain, 'runtime domain');
    assertNonEmptyString(entry.version, `${domain} version`);
    if (!/^[a-z][a-z0-9_]*$/.test(domain)) {
      throw new Error(`CapabilityManifest runtime domain is not a safe TypeScript key: ${domain}`);
    }
    if (Object.prototype.hasOwnProperty.call(metadata, domain)) {
      throw new Error(`CapabilityManifest runtime domain is duplicated: ${domain}`);
    }
    if (!ALLOWED_TIERS.has(entry.requiredTier)) {
      throw new Error(`CapabilityManifest tier is invalid: ${domain}/${entry.requiredTier}`);
    }
    metadata[domain] = {
      name: domain,
      version: entry.version,
      requiredTier: entry.requiredTier,
    };
  }

  if (Object.keys(metadata).length === 0) {
    throw new Error('CapabilityManifest must define at least one runtime capability');
  }
  return metadata;
}

export function serializeCapabilitySkillMetadata(manifest) {
  const metadata = buildCapabilitySkillMetadata(manifest);
  return [
    '// Copyright (c) 2025 Felipe Dominguez. MIT License. See LICENSE.',
    '',
    '// Generated by scripts/generate-capability-skill-metadata.mjs.',
    '// Edit config/capability-manifest.json, then run npm run capabilities:generate.',
    '',
    `export const CAPABILITY_SKILL_METADATA = ${JSON.stringify(metadata, null, 2)} as const;`,
    '',
    'export type CapabilityDomainName = keyof typeof CAPABILITY_SKILL_METADATA;',
    '',
  ].join('\n');
}

function runCli() {
  const root = process.cwd();
  const manifestPath = path.join(root, 'config/capability-manifest.json');
  const outputPath = path.join(root, CAPABILITY_SKILL_METADATA_OUTPUT);
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const serialized = serializeCapabilitySkillMetadata(manifest);
  const check = process.argv.includes('--check');

  if (check) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
    if (current !== serialized) {
      console.error(`${CAPABILITY_SKILL_METADATA_OUTPUT} is stale; run npm run capabilities:generate`);
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, serialized);
  }

  console.log(JSON.stringify({
    ok: true,
    check,
    output: CAPABILITY_SKILL_METADATA_OUTPUT,
    capabilities: Object.keys(buildCapabilitySkillMetadata(manifest)).length,
    manifestSchema: manifest.schema,
  }, null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  runCli();
}
