#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const sources = {
  'docs/agents/DEVELOPMENT_PROCESS.md': 'docs/agents/DEVELOPMENT_PROCESS.md',
  'docs/agents/MODEL_GUIDANCE.md': 'docs/agents/MODEL_GUIDANCE.md',
  'docs/agents/PRODUCT_CONTEXT.md': 'docs/NEXUS_HUB_PRODUCT_BRIEF.md',
};
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const defaultSource = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const git = (root, ...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
const lockName = 'config/development-guidance-lock.json';

export function syncGuidance(source, target) {
  if (fs.realpathSync(source) === fs.realpathSync(target)) throw new Error('Cannot generate copies over canonical sources');
  if (fs.existsSync(path.join(source, lockName))) throw new Error('Regenerate from the canonical backend, not another generated copy');
  const sourceRevision = git(source, 'rev-parse', 'HEAD');
  const sourceState = git(source, 'status', '--porcelain', '--', ...Object.values(sources)) ? 'working-tree' : 'committed';
  const files = {};
  for (const [destination, origin] of Object.entries(sources)) {
    const content = fs.readFileSync(path.join(source, origin));
    const sha256 = digest(content);
    const portable = content.toString().replace(/\[([^\]]+)\]\(([^)]+)\)/g, (full, label, href) => {
      if (/^[a-z]+:/i.test(href) || href.startsWith('#')) return full;
      const [relative, anchor] = href.split('#');
      const sourcePath = path.posix.normalize(path.posix.join(path.posix.dirname(origin), relative));
      const local = Object.entries(sources).find(([, value]) => value === sourcePath)?.[0];
      const targetHref = local ? path.posix.relative(path.posix.dirname(destination), local)
        : `https://github.com/felipedrf74/cortex-telegram-hub-bot/blob/${sourceRevision}/${sourcePath}`;
      return `[${label}](${targetHref}${anchor ? '#' + anchor : ''})`;
    });
    const prefix = `---
kind: development-guidance
status: generated
owner: Felipe
area: operations
repos: [backend, ios, product-docs]
source_role: policy
last_verified: 2026-09-05
review_by: 2026-10-05
work_items: []
supersedes: []
group: operations
---

<!-- Generated by development-guidance.mjs. Source: ${origin}; revision: ${sourceRevision}; state: ${sourceState}; sha256: ${sha256}. Do not edit. -->\n\n`;
    const bytes = Buffer.concat([Buffer.from(prefix), Buffer.from(portable)]);
    const file = path.join(target, destination);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
    files[destination] = { source: origin, sourceSha256: sha256, copySha256: digest(bytes) };
  }
  const checker = fs.readFileSync(path.join(source, 'scripts/development-guidance.mjs'));
  fs.mkdirSync(path.join(target, 'scripts'), { recursive: true });
  fs.writeFileSync(path.join(target, 'scripts/development-guidance.mjs'), checker);
  fs.mkdirSync(path.join(target, 'config'), { recursive: true });
  fs.writeFileSync(path.join(target, lockName), JSON.stringify({ schema: 'nexus.development-guidance.v1', repository: 'felipedrf74/cortex-telegram-hub-bot', sourceRevision, sourceState, checkerSha256: digest(checker), files }, null, 2) + '\n');
}

export function checkGuidance(target, source = null) {
  const errors = [];
  const lockPath = path.join(target, lockName);
  if (fs.existsSync(lockPath)) {
    const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
    if (!fs.existsSync(path.join(target, 'scripts/development-guidance.mjs')) || digest(fs.readFileSync(path.join(target, 'scripts/development-guidance.mjs'))) !== lock.checkerSha256) errors.push('Guidance checker drift');
    if (lock.schema !== 'nexus.development-guidance.v1' || Object.keys(lock.files || {}).sort().join() !== Object.keys(sources).sort().join()) errors.push('Invalid guidance lock');
    for (const [file, origin] of Object.entries(sources)) {
      const entry = lock.files?.[file];
      if (entry?.source !== origin || !fs.existsSync(path.join(target, file)) || digest(fs.readFileSync(path.join(target, file))) !== entry.copySha256) errors.push(`Generated copy drift: ${file}`);
      if (source && entry?.sourceSha256 !== digest(fs.readFileSync(path.join(source, origin)))) errors.push(`Source revision drift: ${file}`);
    }
  } else if (source && fs.realpathSync(source) !== fs.realpathSync(target)) errors.push('Missing guidance lock');
  const active = ['AGENTS.md', 'CLAUDE.md', 'docs/DOCS_INDEX.md', 'docs/agents/DEVELOPMENT_PROCESS.md', ...Object.keys(sources).filter(file => fs.existsSync(path.join(target, file)))];
  for (const file of active) {
    const absolute = path.join(target, file);
    if (!fs.existsSync(absolute)) { if (file !== 'docs/DOCS_INDEX.md') errors.push(`Missing entrypoint: ${file}`); continue; }
    const content = fs.readFileSync(absolute, 'utf8');
    if (/AGENT_TECHNICAL_MASTERY|ios-specs\/00-CURRENT-PRODUCT-TRUTH|docs\/release\/CURRENT_RELEASE_STATE\.md`.*workspace/i.test(content)) errors.push(`Retired context pointer: ${file}`);
    for (const match of content.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)) {
      const href = match[1].split('#')[0];
      if (!href || /^[a-z]+:/i.test(href)) continue;
      if (href.startsWith('/') || !fs.existsSync(path.resolve(path.dirname(absolute), href))) errors.push(`Unavailable local link: ${file} -> ${href}`);
    }
  }
  for (const required of ['docs/agents/DEVELOPMENT_PROCESS.md', 'docs/agents/MODEL_GUIDANCE.md']) if (!fs.existsSync(path.join(target, required))) errors.push(`Missing shared guidance: ${required}`);
  const claude = path.join(target, '.claude/skills');
  if (fs.existsSync(claude)) for (const name of fs.readdirSync(claude)) {
    if (!fs.existsSync(path.join(claude, name, 'SKILL.md'))) errors.push(`Broken Claude skill: ${name}`);
  }
  return errors;
}

export function startup(root) {
  const value = { root, head: git(root, 'rev-parse', 'HEAD'), branch: git(root, 'branch', '--show-current'), dirty: Boolean(git(root, 'status', '--porcelain')), base: null, behind: null, freshness: 'local_refs_only' };
  try { value.base = git(root, 'rev-parse', 'origin/main'); value.behind = Number(git(root, 'rev-list', '--count', 'HEAD..origin/main')); } catch { /* Offline workspace may have no remote. */ }
  value.policySha256 = digest(fs.readFileSync(path.join(root, 'docs/agents/DEVELOPMENT_PROCESS.md')));
  return value;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2);
    const option = name => { const i = args.indexOf(name); return i < 0 ? null : args[i + 1]; };
    const target = path.resolve(option('--target') || process.cwd());
    const source = path.resolve(option('--source') || defaultSource);
    if (args.includes('--sync')) syncGuidance(source, target);
    const localCopy = target === defaultSource && fs.existsSync(path.join(target, lockName)) && !option('--source');
    const errors = checkGuidance(target, args.includes('--offline') || localCopy ? null : source);
    console.log(JSON.stringify({ status: errors.length ? 'FAIL' : 'PASS', errors, ...(args.includes('--startup') ? { checkout: startup(target) } : {}) }, null, 2));
    if (errors.length) process.exitCode = 1;
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
